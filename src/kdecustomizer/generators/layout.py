"""Plasma desktop layout script (JS, run by plasmashell's scripting engine).

Used both inside the Look-and-Feel package (contents/layouts/org.kde.plasma.desktop-layout.js)
and standalone via `qdbus6 org.kde.plasmashell /PlasmaShell evaluateScript`.
"""
from __future__ import annotations

import json

from ..spec import Theme

def generate(theme: Theme, reset: bool = True) -> str:
    """Panels only. The wallpaper is set by install.sh (plasma-apply-wallpaperimage) so the
    path resolves on whichever machine installs the theme."""
    js: list[str] = ["// Generated by kde-customizer — edits will be overwritten."]
    if reset:
        js.append("panels().forEach(function (p) { p.remove(); });")

    for i, p in enumerate(theme.panels):
        v = f"panel{i}"
        js += [
            f"var {v} = new Panel;",
            f"{v}.location = {json.dumps(p.location)};",
            f"{v}.height = {int(p.height)};",
            f"{v}.floating = {str(p.floating).lower()};",
            f"{v}.alignment = {json.dumps(p.alignment)};",
            f"{v}.lengthMode = {json.dumps(p.length_mode)};",
        ]
        for w in p.widgets:
            js.append(f"{v}.addWidget({json.dumps(w)});")
    return "\n".join(js) + "\n"
