"""GTK 4 / libadwaita (GNOME) apps in the palette: `~/.config/gtk-4.0/kde-customizer.css`.

libadwaita ignores KDE color schemes (KDE's GTK integration only writes `*_breeze` colors for the Breeze GTK
theme into gtk-4.0/colors.css), but every GTK 4 app loads the user's `gtk-4.0/gtk.css`. install.sh imports our
file from there, after KDE's `colors.css`, so these colors win. Written twice:
- CSS custom properties (`--window-bg-color`, libadwaita 1.6+ / GTK 4.16+ — this box has 1.10),
- named colors (`@define-color window_bg_color`, older libadwaita in Flatpak runtimes; also what app CSS uses).
Colors come from colors.scheme(), the same roles the KDE color scheme uses.
"""
from __future__ import annotations

from ..color import RGB, contrast, luminance, mix, parse, shift, to_hex
from ..spec import Theme
from . import colors as colors_gen

FILE = "kde-customizer.css"
IMPORT = f"@import '{FILE}';"


def _hex(c: RGB | str) -> str:
    return c if isinstance(c, str) else to_hex(c)


def _on(c: RGB | str) -> str:
    """Text color on a filled background."""
    return "#ffffff" if luminance(c) < 0.4 else "rgba(0, 0, 0, 0.8)"


def _readable(c: RGB | str, bg: RGB | str, dark: bool) -> str:
    """`c` moved toward the text color until it reads on `bg` (accent/status colors used as text)."""
    out = parse(c) if isinstance(c, str) else c
    for _ in range(10):
        if contrast(out, bg) >= 3.0:
            break
        out = shift(out, 0.12, dark)
    return to_hex(out)


def colors(theme: Theme) -> dict[str, str]:
    """libadwaita color variable (without --/-color) -> CSS color."""
    s = colors_gen.scheme(theme)
    p = theme.palette.resolved()
    dark = theme.dark
    win, view, head, sel = s["Colors:Window"], s["Colors:View"], s["Colors:Header"], s["Colors:Selection"]
    wbg, wfg, vbg = win["BackgroundNormal"], win["ForegroundNormal"], view["BackgroundNormal"]
    shade = "rgba(0, 0, 0, 0.36)" if dark else "rgba(0, 0, 0, 0.07)"
    raised = shift(wbg, 0.06, dark)
    c = {
        "accent-bg": _hex(sel["BackgroundNormal"]),
        "accent-fg": _hex(sel["ForegroundNormal"]),
        "accent": _readable(p.accent, vbg, dark),
        "window-bg": _hex(wbg), "window-fg": _hex(wfg),
        "view-bg": _hex(vbg), "view-fg": _hex(view["ForegroundNormal"]),
        "headerbar-bg": _hex(head["BackgroundNormal"]), "headerbar-fg": _hex(head["ForegroundNormal"]),
        "headerbar-border": _hex(head["ForegroundNormal"]),
        "headerbar-backdrop": _hex(wbg),
        "headerbar-shade": shade, "headerbar-darker-shade": shade,
        "sidebar-bg": _hex(p.surface), "sidebar-fg": _hex(wfg), "sidebar-backdrop": _hex(p.surface),
        "sidebar-border": shade, "sidebar-shade": shade,
        "secondary-sidebar-bg": _hex(p.surface), "secondary-sidebar-fg": _hex(wfg),
        "secondary-sidebar-backdrop": _hex(p.surface), "secondary-sidebar-border": shade,
        "secondary-sidebar-shade": shade,
        "card-bg": to_hex(mix(vbg, wfg, 0.06)), "card-fg": _hex(wfg), "card-shade": shade,
        "dialog-bg": to_hex(raised), "dialog-fg": _hex(wfg),
        "popover-bg": to_hex(raised), "popover-fg": _hex(wfg), "popover-shade": shade,
        "thumbnail-bg": _hex(vbg), "thumbnail-fg": _hex(wfg),
        "shade": shade,
        "scrollbar-outline": "rgba(0, 0, 0, 0.5)" if dark else "#ffffff",
    }
    for name, base in (("destructive", p.negative), ("error", p.negative), ("success", p.positive),
                       ("warning", p.neutral)):
        c[f"{name}-bg"] = _hex(base)
        c[f"{name}-fg"] = _on(base)
        c[name] = _readable(base, vbg, dark)
    return c


def css(theme: Theme) -> str:
    c = colors(theme)
    lines = [f"/* {theme.name}: GTK 4 / libadwaita colors, generated by kde-customizer. */",
             "/* Imported from gtk.css; delete the @import line there to go back to stock colors. */", "",
             ":root {"]
    lines += [f"  --{k}-color: {v};" for k, v in c.items()]
    lines += ["}", "", "/* libadwaita < 1.6 and app stylesheets use the named colors */"]
    lines += [f"@define-color {k.replace('-', '_')}_color {v};" for k, v in c.items()]
    return "\n".join(lines) + "\n"
