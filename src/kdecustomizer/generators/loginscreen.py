"""Login screen — the theme's look on the login greeter: Plasma Login Manager (Plasma 6.6+) or SDDM.

Both greeters run as a system user (`plasmalogin` / `sddm`) with no theme packages of their own: they read
that user's `~/.config/kdeglobals` (colors, icons, fonts), `plasmarc` (Plasma style) and `kcminputrc` (cursors)
— the files System Settings' "Apply Plasma Settings" copies there — and anything under its `~/.local/share`.
- Plasma Login: wallpaper in `/etc/plasmalogin.conf` `[Greeter][Wallpaper][<plugin>][General]`, images in
  `~plasmalogin/wallpapers/`.
- SDDM (Breeze SDDM theme, from plasma-desktop): `/etc/sddm.conf.d/kde_settings.conf` `[Theme]` Current /
  CursorTheme / Font; background + clock in the theme's `theme.conf.user` (what sddm-kcm writes).

Two scripts, both plain bash so built themes stay installable without this tool:
- `apply.sh` (root, via pkexec): picks the display manager in use, stages the generated assets somewhere the
  greeter user can read, runs `greeter.sh` as that user, writes the system config.
- `greeter.sh` (as the greeter user): copies the assets into its ~/.local/share, merges our keys into its
  config with kwriteconfig6 (keyboard layout, screen setup etc. synced there stay), clears its cache.

Test hooks (not for normal use): KDEC_LOGIN_ROOT=<dir> prefixes /etc and /usr/share and runs greeter.sh as the
caller in KDEC_LOGIN_HOME; KDEC_LOGIN_DM=plasmalogin|sddm forces the display manager.
"""
from __future__ import annotations

import re
import shlex
from pathlib import Path

from ..color import parse
from ..spec import Theme
from . import colors as colors_gen

GREETER_USERS = ("plasmalogin", "sddm")
SDDM_THEME = "breeze"
_GROUP = re.compile(r"\[([^\]]+)\]")


def _ini(text: str) -> list[tuple[list[str], str, str]]:
    """(groups, key, value) for every entry of a KConfig file; nested groups as [A][B]."""
    out, groups = [], []
    for line in text.splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        if line.startswith("["):
            groups = _GROUP.findall(line)
        elif "=" in line and groups:
            k, v = line.split("=", 1)
            out.append((groups, k.strip(), v.strip()))
    return out


def entries(theme: Theme, font_keys: dict[str, tuple[str, str, str]], qfont) -> list[tuple[str, list[str], str, str]]:
    """(file, groups, key, value) written into the greeter user's config."""
    e = [("kdeglobals", g, k, v) for g, k, v in _ini(colors_gen.generate(theme))]
    e.append(("kdeglobals", ["Icons"], "Theme", theme.icons_name))
    for field, (f, g, k) in font_keys.items():
        val = getattr(theme.fonts, field)
        if val and f == "kdeglobals":
            e.append((f, [g], k, qfont(val)))
    e.append(("plasmarc", ["Theme"], "name", theme.plasma_style_name))
    e.append(("kcminputrc", ["Mouse"], "cursorTheme", theme.cursors_name))
    return e


def wallpaper_name(theme: Theme) -> str | None:
    """File name of the wallpaper on the login screen, or None for a solid palette color."""
    if theme.login_screen.background == "wallpaper" and theme.wallpaper:
        return Path(theme.wallpaper).name
    return None


def _kw(file: str, groups: list[str], key: str, value: str) -> str:
    g = " ".join(f"--group {shlex.quote(x)}" for x in groups)
    return f"kwriteconfig6 --file {file} {g} --key {shlex.quote(key)} {shlex.quote(value)}"


def greeter_script(theme: Theme, font_keys, qfont) -> str:
    q = shlex.quote
    s = [
        "#!/usr/bin/env bash",
        f"# Runs as the login greeter's user (apply.sh starts it). Generated by kde-customizer for {theme.name}.",
        "set -euo pipefail",
        'S="$1"',
        'C="$HOME/.config"; D="$HOME/.local/share"',
        "# the greeter keeps rendered Plasma SVGs/colors in its cache: drop it so new colors show",
        'rm -rf "$HOME/.cache"',
        'mkdir -p "$C" "$D/plasma/desktoptheme" "$D/icons"',
        'for d in "$S"/share/plasma/desktoptheme/* "$S"/share/icons/*; do',
        '  [[ -e "$d" ]] || continue',
        '  rel="${d#"$S"/share/}"',
        '  rm -rf "$D/$rel"',
        '  cp -r "$d" "$D/$rel"',
        "done",
    ]
    if wp := wallpaper_name(theme):
        s += ['mkdir -p "$HOME/wallpapers"', f'cp "$S/wallpapers/"{q(wp)} "$HOME/wallpapers/"']
    for file, groups, key, value in entries(theme, font_keys, qfont):
        s.append(_kw(f'"$C/{file}"', groups, key, value))
    return "\n".join(s) + "\n"


def root_script(theme: Theme) -> str:
    """apply.sh <build dir>: run as root."""
    q = shlex.quote
    stage = []
    if theme.plasma.generate:
        stage.append(f'cp -r "$DIR/plasma/"{q(theme.plasma_style_name)} "$STAGE/share/plasma/desktoptheme/"')
    if theme.iconset.generate:
        stage.append(f'cp -r "$DIR/icons/"{q(theme.icons_name)} "$STAGE/share/icons/"')
    if theme.cursorset.generate:
        stage.append(f'cp -r "$DIR/cursors/"{q(theme.cursors_name)} "$STAGE/share/icons/"')
    wp = wallpaper_name(theme)
    if wp:
        stage.append(f'cp "$DIR/wallpapers/"{q(wp)} "$STAGE/wallpapers/"')
    r, g, b = parse(theme.palette.background)
    clock = "true" if theme.login_screen.clock else "false"

    plm_conf = '"$ROOT/etc/plasmalogin.conf"'
    plm = [_kw(plm_conf, ["Greeter"], "ShowClock", clock)]
    if wp:
        plm += [_kw(plm_conf, ["Greeter"], "WallpaperPluginId", "org.kde.image"),
                f'kwriteconfig6 --file {plm_conf} --group Greeter --group Wallpaper --group org.kde.image '
                f'--group General --key Image "file://$GHOME/wallpapers/"{q(wp)}']
    else:
        plm += [_kw(plm_conf, ["Greeter"], "WallpaperPluginId", "org.kde.color"),
                _kw(plm_conf, ["Greeter", "Wallpaper", "org.kde.color", "General"], "Color", f"{r},{g},{b}")]
    plm.append(f"chmod 644 {plm_conf}")

    kde = '"$ROOT/etc/sddm.conf.d/kde_settings.conf"'
    user = '"$THEME_DIR/theme.conf.user"'
    sddm = [
        'mkdir -p "$ROOT/etc/sddm.conf.d"',
        _kw(kde, ["Theme"], "CursorTheme", theme.cursors_name),
    ]
    if theme.fonts.general:
        from .konsole import _qfont
        sddm.append(_kw(kde, ["Theme"], "Font", _qfont(theme.fonts.general)))
    sddm += [
        f'THEME_DIR="$ROOT/usr/share/sddm/themes/{SDDM_THEME}"',
        'if [[ -d "$THEME_DIR" ]]; then',
        "  " + _kw(kde, ["Theme"], "Current", SDDM_THEME),
        "  " + _kw(user, ["General"], "showClock", clock),
        "  " + _kw(user, ["General"], "color", theme.palette.background),
    ]
    if wp:
        ext = Path(wp).suffix.lower()
        sddm += [
            f'  install -m 644 "$STAGE/wallpapers/"{q(wp)} "$THEME_DIR/kde-customizer-background{ext}"',
            "  " + _kw(user, ["General"], "type", "image"),
            f'  kwriteconfig6 --file {user} --group General --key background '
            f'"/usr/share/sddm/themes/{SDDM_THEME}/kde-customizer-background{ext}"',
        ]
    else:
        sddm.append("  " + _kw(user, ["General"], "type", "color"))
    sddm += [
        f"  chmod 644 {user}",
        "else",
        f'  echo "The {SDDM_THEME} SDDM theme is not installed (it comes with plasma-desktop): '
        'set colors and cursors only."',
        "fi",
        f"chmod 644 {kde}",
    ]
    ind = lambda lines: ["  " + x for x in lines]   # noqa: E731

    s = [
        "#!/usr/bin/env bash",
        f"# Puts the '{theme.name}' look on the login screen (Plasma Login Manager or SDDM).",
        "# Run as root: apply.sh <theme build dir>. Generated by kde-customizer.",
        "set -euo pipefail",
        'DIR="$(cd "$1" && pwd)"',
        'ROOT="${KDEC_LOGIN_ROOT:-}"',
        "# the display manager in use; fall back to whichever greeter user exists",
        'DM="${KDEC_LOGIN_DM:-$(basename "$(readlink -f /etc/systemd/system/display-manager.service 2>/dev/null)" '
        '.service 2>/dev/null || true)}"',
        'case "$DM" in',
        "  plasmalogin|sddm) ;;",
        '  *) DM=""; for u in plasmalogin sddm; do getent passwd "$u" >/dev/null && { DM="$u"; break; }; done ;;',
        "esac",
        'if [[ -z "$DM" ]]; then echo "No Plasma Login Manager or SDDM found: login screen left as is." >&2; exit 1; fi',
        'GUSER="$DM"',
        'GHOME="${KDEC_LOGIN_HOME:-$(getent passwd "$GUSER" | cut -d: -f6)}"',
        'if [[ -z "$GHOME" || ! -d "$GHOME" ]]; then echo "no home for the $GUSER user" >&2; exit 1; fi',
        "# stage in a place the greeter user can read (the build dir may be in a private home)",
        'STAGE="$(mktemp -d)"',
        "trap 'rm -rf \"$STAGE\"' EXIT",
        'mkdir -p "$STAGE/share/plasma/desktoptheme" "$STAGE/share/icons" "$STAGE/wallpapers"',
        *stage,
        'cp "$DIR/login/greeter.sh" "$STAGE/"',
        'chmod -R a+rX "$STAGE"',
        'if [[ -n "$ROOT" ]]; then',
        '  HOME="$GHOME" bash "$STAGE/greeter.sh" "$STAGE"',
        "else",
        "  # files left owned by root (Plasma 6.6, older sync tools) would stop the greeter user writing",
        '  chown -R -P "$GUSER:" "$GHOME"',
        '  runuser -u "$GUSER" -- env HOME="$GHOME" bash "$STAGE/greeter.sh" "$STAGE"',
        "fi",
        'if [[ "$DM" == plasmalogin ]]; then',
        *ind(plm),
        "else",
        *ind(sddm),
        "fi",
        'echo "Login screen ($DM) updated; it shows on the next login."',
    ]
    return "\n".join(s) + "\n"
