"""Login screen — the theme's look on the Plasma Login Manager greeter (Plasma 6.6+, the SDDM successor).

The greeter is a compiled QML app running as the `plasmalogin` user, so it has no theme packages of its own:
it reads that user's `~/.config/kdeglobals` (colors, icons, fonts), `plasmarc` (Plasma style) and
`kcminputrc` (cursors) — the same files System Settings' "Apply Plasma Settings" copies there — and anything
under its `~/.local/share`. The wallpaper comes from `/etc/plasmalogin.conf`
`[Greeter][Wallpaper][<plugin>][General]`, with images kept in `~plasmalogin/wallpapers/`.

Two scripts, both plain bash so built themes stay installable without this tool:
- `apply.sh` (root, via pkexec): stages the generated assets somewhere the greeter user can read, runs
  `greeter.sh` as that user, writes the wallpaper keys into /etc/plasmalogin.conf.
- `greeter.sh` (as plasmalogin): copies the assets into its ~/.local/share, merges our keys into its
  config with kwriteconfig6 (keyboard layout, screen setup etc. synced there stay), clears its cache.
"""
from __future__ import annotations

import re
import shlex
from pathlib import Path

from ..color import parse
from ..spec import Theme
from . import colors as colors_gen

GREETER_USER = "plasmalogin"
CONF = "/etc/plasmalogin.conf"
_GROUP = re.compile(r"\[([^\]]+)\]")


def _ini(text: str) -> list[tuple[list[str], str, str]]:
    """(groups, key, value) for every entry of a KConfig file; nested groups as [A][B]."""
    out, groups = [], []
    for line in text.splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        if line.startswith("["):
            groups = _GROUP.findall(line)
        elif "=" in line and groups:
            k, v = line.split("=", 1)
            out.append((groups, k.strip(), v.strip()))
    return out


def entries(theme: Theme, font_keys: dict[str, tuple[str, str, str]], qfont) -> list[tuple[str, list[str], str, str]]:
    """(file, groups, key, value) written into the greeter user's config."""
    e = [("kdeglobals", g, k, v) for g, k, v in _ini(colors_gen.generate(theme))]
    e.append(("kdeglobals", ["Icons"], "Theme", theme.icons_name))
    for field, (f, g, k) in font_keys.items():
        val = getattr(theme.fonts, field)
        if val and f == "kdeglobals":
            e.append((f, [g], k, qfont(val)))
    e.append(("plasmarc", ["Theme"], "name", theme.plasma_style_name))
    e.append(("kcminputrc", ["Mouse"], "cursorTheme", theme.cursors_name))
    return e


def wallpaper_name(theme: Theme) -> str | None:
    """File name of the wallpaper on the login screen, or None for a solid palette color."""
    if theme.login_screen.background == "wallpaper" and theme.wallpaper:
        return Path(theme.wallpaper).name
    return None


def _kw(file: str, groups: list[str], key: str, value: str) -> str:
    g = " ".join(f"--group {shlex.quote(x)}" for x in groups)
    return f"kwriteconfig6 --file {file} {g} --key {shlex.quote(key)} {shlex.quote(value)}"


def greeter_script(theme: Theme, font_keys, qfont) -> str:
    q = shlex.quote
    s = [
        "#!/usr/bin/env bash",
        f"# Runs as the '{GREETER_USER}' user (apply.sh starts it). Generated by kde-customizer for {theme.name}.",
        "set -euo pipefail",
        'S="$1"',
        'C="$HOME/.config"; D="$HOME/.local/share"',
        "# the greeter keeps rendered Plasma SVGs/colors in its cache: drop it so new colors show",
        'rm -rf "$HOME/.cache"',
        'mkdir -p "$C" "$D/plasma/desktoptheme" "$D/icons"',
        'for d in "$S"/share/plasma/desktoptheme/* "$S"/share/icons/*; do',
        '  [[ -e "$d" ]] || continue',
        '  rel="${d#"$S"/share/}"',
        '  rm -rf "$D/$rel"',
        '  cp -r "$d" "$D/$rel"',
        "done",
    ]
    if wp := wallpaper_name(theme):
        s += ['mkdir -p "$HOME/wallpapers"', f'cp "$S/wallpapers/"{q(wp)} "$HOME/wallpapers/"']
    for file, groups, key, value in entries(theme, font_keys, qfont):
        s.append(_kw(f'"$C/{file}"', groups, key, value))
    return "\n".join(s) + "\n"


def root_script(theme: Theme) -> str:
    """apply.sh <build dir>: run as root."""
    q = shlex.quote
    stage = []
    if theme.plasma.generate:
        stage.append(f'cp -r "$DIR/plasma/"{q(theme.plasma_style_name)} "$STAGE/share/plasma/desktoptheme/"')
    if theme.iconset.generate:
        stage.append(f'cp -r "$DIR/icons/"{q(theme.icons_name)} "$STAGE/share/icons/"')
    if theme.cursorset.generate:
        stage.append(f'cp -r "$DIR/cursors/"{q(theme.cursors_name)} "$STAGE/share/icons/"')
    wp = wallpaper_name(theme)
    if wp:
        stage.append(f'cp "$DIR/wallpapers/"{q(wp)} "$STAGE/wallpapers/"')
        wall = [
            _kw(CONF, ["Greeter"], "WallpaperPluginId", "org.kde.image"),
            f'kwriteconfig6 --file {CONF} --group Greeter --group Wallpaper --group org.kde.image --group General '
            f'--key Image "file://$GHOME/wallpapers/"{q(wp)}',
        ]
    else:
        r, g, b = parse(theme.palette.background)
        wall = [
            _kw(CONF, ["Greeter"], "WallpaperPluginId", "org.kde.color"),
            _kw(CONF, ["Greeter", "Wallpaper", "org.kde.color", "General"], "Color", f"{r},{g},{b}"),
        ]
    s = [
        "#!/usr/bin/env bash",
        f"# Puts the '{theme.name}' look on the Plasma Login screen. Run as root: apply.sh <theme build dir>.",
        "# Generated by kde-customizer.",
        "set -euo pipefail",
        'DIR="$(cd "$1" && pwd)"',
        f"GUSER={GREETER_USER}",
        'GHOME="$(getent passwd "$GUSER" | cut -d: -f6)"',
        'if [[ -z "$GHOME" || ! -d "$GHOME" ]]; then echo "no $GUSER user: is Plasma Login Manager installed?" >&2; exit 1; fi',
        "# files owned by root from Plasma 6.6 would stop the greeter user writing (System Settings fixes this too)",
        'chown -R -P "$GUSER:" "$GHOME"',
        "# stage in a place the greeter user can read (the build dir may be in a private home)",
        'STAGE="$(mktemp -d)"',
        "trap 'rm -rf \"$STAGE\"' EXIT",
        'mkdir -p "$STAGE/share/plasma/desktoptheme" "$STAGE/share/icons" "$STAGE/wallpapers"',
        *stage,
        'cp "$DIR/login/greeter.sh" "$STAGE/"',
        'chmod -R a+rX "$STAGE"',
        'runuser -u "$GUSER" -- env HOME="$GHOME" bash "$STAGE/greeter.sh" "$STAGE"',
        *wall,
        _kw(CONF, ["Greeter"], "ShowClock", "true" if theme.login_screen.clock else "false"),
        f"chmod 644 {CONF}",
        'echo "Login screen updated; it shows on the next login."',
    ]
    return "\n".join(s) + "\n"
