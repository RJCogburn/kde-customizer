"""Splash screen — `contents/splash/Splash.qml` inside the Look-and-Feel package.

ksplashqml loads the LnF's Splash.qml full screen and raises its `stage` property from 1 to 6 as the
session starts (Breeze fades in at stage 2). Ours: the theme name (or `text`) in the palette's
foreground, and a thin accent bar that fills with the stages, over a palette gradient, the theme's
wallpaper (dimmed so the text reads) or a solid background. Only QtQuick + Kirigami units are used.
"""
from __future__ import annotations

import json
from pathlib import Path

from ..color import RGB, mix, parse, to_hex
from ..spec import Theme

STAGES = 6


def _q(s: str) -> str:
    """QML string literal."""
    return json.dumps(s, ensure_ascii=False)


def _argb(c: RGB, a: float) -> str:
    """QML color with alpha: #AARRGGBB."""
    return f"#{round(a * 255):02x}{to_hex(c)[1:]}"


def background_file(theme: Theme) -> str | None:
    """Name the wallpaper gets inside contents/splash/images/, when it's used."""
    if theme.splash_screen.background == "wallpaper" and theme.wallpaper:
        return "background" + Path(theme.wallpaper).suffix.lower()
    return None


def qml(theme: Theme) -> str:
    """Splash.qml for ksplashqml: background (gradient, wallpaper or solid), name, progress bar following `stage`."""
    p = theme.palette.resolved()
    bg, fg, acc = parse(p.background), parse(p.foreground), parse(p.accent)
    text = theme.splash_screen.text or theme.name
    family = theme.fonts.general.split(",")[0].strip() if theme.fonts.general else ""
    image = background_file(theme)
    mode = theme.splash_screen.background
    if mode == "wallpaper" and not image:
        mode = "gradient"                      # no wallpaper to show

    if mode == "wallpaper":
        backdrop = f"""
    Image {{
        anchors.fill: parent
        source: "images/{image}"
        fillMode: Image.PreserveAspectCrop
        asynchronous: true
    }}
    Rectangle {{
        anchors.fill: parent
        // dim the picture toward the background so the text stays readable
        gradient: Gradient {{
            GradientStop {{ position: 0.0; color: "{_argb(bg, 0.45)}" }}
            GradientStop {{ position: 0.5; color: "{_argb(bg, 0.7)}" }}
            GradientStop {{ position: 1.0; color: "{_argb(bg, 0.85)}" }}
        }}
    }}"""
    elif mode == "gradient":
        backdrop = f"""
    Rectangle {{
        anchors.fill: parent
        gradient: Gradient {{
            GradientStop {{ position: 0.0; color: "{to_hex(bg)}" }}
            GradientStop {{ position: 0.65; color: "{to_hex(mix(bg, acc, 0.08))}" }}
            GradientStop {{ position: 1.0; color: "{to_hex(mix(bg, acc, 0.22))}" }}
        }}
    }}"""
    else:
        backdrop = ""

    font = f"\n                font.family: {_q(family)}" if family else ""
    return f"""// Generated by kde-customizer for {theme.name}. ksplashqml raises `stage` from 1 to {STAGES}.
import QtQuick
import org.kde.kirigami as Kirigami

Rectangle {{
    id: root
    color: "{to_hex(bg)}"

    property int stage
    // grid units don't grow with resolution; keep the text a fixed share of the screen height
    readonly property real unit: Math.max(Kirigami.Units.gridUnit, height / 48)

    onStageChanged: {{
        // fade in from stage 2 on (also if a stage is skipped)
        if (stage >= 2 && content.opacity == 0 && !introAnimation.running) {{
            introAnimation.running = true;
        }}
    }}
{backdrop}

    Item {{
        id: content
        anchors.fill: parent
        opacity: 0

        Column {{
            anchors.centerIn: parent
            spacing: root.unit * 1.5

            Text {{
                anchors.horizontalCenter: parent.horizontalCenter
                text: {_q(text)}
                color: "{to_hex(fg)}"{font}
                font.pixelSize: root.unit * 2.6
                font.weight: Font.Light
                font.letterSpacing: root.unit * 0.08
                textFormat: Text.PlainText
                Accessible.name: text
                Accessible.role: Accessible.StaticText
            }}

            Rectangle {{
                id: track
                anchors.horizontalCenter: parent.horizontalCenter
                width: root.unit * 14
                height: Math.max(3, Math.round(root.unit * 0.22))
                radius: height / 2
                color: "{_argb(fg, 0.14)}"

                Rectangle {{
                    height: parent.height
                    radius: parent.radius
                    color: "{to_hex(acc)}"
                    width: parent.width * Math.min(root.stage, {STAGES}) / {STAGES}
                    Behavior on width {{
                        NumberAnimation {{
                            duration: Kirigami.Units.longDuration * 3
                            easing.type: Easing.OutCubic
                        }}
                    }}
                }}
            }}
        }}
    }}

    OpacityAnimator {{
        id: introAnimation
        running: false
        target: content
        from: 0
        to: 1
        duration: Kirigami.Units.veryLongDuration * 2
        easing.type: Easing.InOutQuad
    }}
}}
"""
