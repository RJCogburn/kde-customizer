"""Other terminals and editors in the theme: kitty, Alacritty, WezTerm, Ghostty, VS Code (and VSCodium/Code-OSS).

Terminal colors come from konsole.ansi() — the same 16 colors + background/foreground as the Konsole scheme —
and VS Code's workbench from colors.scheme(), so every app matches the KDE color scheme.
install.sh only touches apps that are installed, keeps the user's config files (marked blocks / commented
lines that a theme without [apps] undoes again) and never edits VS Code's settings (JSON with comments).
"""
from __future__ import annotations

import io
import json
import re
import zipfile

from ..color import RGB, mix, to_hex
from ..spec import Theme
from . import colors as colors_gen
from . import konsole

ANSI_NAMES = ["black", "red", "green", "yellow", "blue", "magenta", "cyan", "white"]


def _ansi(theme: Theme) -> dict[str, str]:
    """background, foreground, color0..color15 as #rrggbb."""
    a = konsole.ansi(theme)
    out = {"background": to_hex(a["Background"]), "foreground": to_hex(a["Foreground"])}
    for i in range(8):
        out[f"color{i}"] = to_hex(a[f"Color{i}"])
        out[f"color{i + 8}"] = to_hex(a[f"Color{i}Intense"])
    return out


def _accent(theme: Theme) -> tuple[str, str]:
    """(accent, text on accent)."""
    sel = colors_gen.scheme(theme)["Colors:Selection"]
    return _h(sel["BackgroundNormal"]), _h(sel["ForegroundNormal"])


def kitty(theme: Theme) -> str:
    c, (acc, on) = _ansi(theme), _accent(theme)
    lines = [f"# {theme.name}, generated by kde-customizer", f"background {c['background']}",
             f"foreground {c['foreground']}", f"cursor {acc}", f"cursor_text_color {c['background']}",
             f"selection_background {acc}", f"selection_foreground {on}", f"url_color {acc}",
             f"active_border_color {acc}", f"inactive_border_color {c['color8']}",
             f"active_tab_background {acc}", f"active_tab_foreground {on}",
             f"inactive_tab_background {c['background']}", f"inactive_tab_foreground {c['color7']}"]
    lines += [f"color{i} {c[f'color{i}']}" for i in range(16)]
    return "\n".join(lines) + "\n"


def alacritty(theme: Theme) -> str:
    c, (acc, on) = _ansi(theme), _accent(theme)
    out = [f"# {theme.name}, generated by kde-customizer. Imported from alacritty.toml.", "",
           "[colors.primary]", f'background = "{c["background"]}"', f'foreground = "{c["foreground"]}"', "",
           "[colors.cursor]", f'text = "{c["background"]}"', f'cursor = "{acc}"', "",
           "[colors.selection]", f'text = "{on}"', f'background = "{acc}"', ""]
    for table, base in (("normal", 0), ("bright", 8)):
        out.append(f"[colors.{table}]")
        out += [f'{n} = "{c[f"color{base + i}"]}"' for i, n in enumerate(ANSI_NAMES)]
        out.append("")
    return "\n".join(out)


def wezterm(theme: Theme) -> str:
    c, (acc, on) = _ansi(theme), _accent(theme)
    q = lambda xs: "[" + ", ".join(f'"{x}"' for x in xs) + "]"   # noqa: E731
    return "\n".join([
        "[colors]",
        f'background = "{c["background"]}"', f'foreground = "{c["foreground"]}"',
        f'cursor_bg = "{acc}"', f'cursor_border = "{acc}"', f'cursor_fg = "{c["background"]}"',
        f'selection_bg = "{acc}"', f'selection_fg = "{on}"',
        f"ansi = {q(c[f'color{i}'] for i in range(8))}",
        f"brights = {q(c[f'color{i}'] for i in range(8, 16))}",
        "", "[metadata]", f'name = "{theme.name}"', 'author = "kde-customizer"', "",
    ])


def ghostty(theme: Theme) -> str:
    c, (acc, on) = _ansi(theme), _accent(theme)
    lines = [f"# {theme.name}, generated by kde-customizer"]
    lines += [f"palette = {i}={c[f'color{i}']}" for i in range(16)]
    lines += [f"background = {c['background']}", f"foreground = {c['foreground']}", f"cursor-color = {acc}",
              f"selection-background = {acc}", f"selection-foreground = {on}"]
    return "\n".join(lines) + "\n"


# --- VS Code ------------------------------------------------------------------------------------------

def _h(c: RGB | str, alpha: float | None = None) -> str:
    s = c if isinstance(c, str) else to_hex(c)
    return s + (f"{round(alpha * 255):02x}" if alpha is not None else "")


def vscode_theme(theme: Theme) -> dict:
    s = colors_gen.scheme(theme)
    p = theme.palette.resolved()
    win, view, head, btn, sel = (s["Colors:Window"], s["Colors:View"], s["Colors:Header"], s["Colors:Button"],
                                 s["Colors:Selection"])
    wm = s["WM"]
    a = _ansi(theme)
    acc, on = _h(sel["BackgroundNormal"]), _h(sel["ForegroundNormal"])
    fg, vbg, wbg = _h(view["ForegroundNormal"]), _h(view["BackgroundNormal"]), _h(win["BackgroundNormal"])
    dim = _h(win["ForegroundInactive"])
    line = _h(mix(view["BackgroundNormal"], view["ForegroundNormal"], 0.05))
    border = _h(mix(win["BackgroundNormal"], win["ForegroundNormal"], 0.12))
    colors = {
        "focusBorder": acc, "foreground": _h(win["ForegroundNormal"]), "descriptionForeground": dim,
        "errorForeground": _h(p.negative), "textLink.foreground": _h(p.link), "textLink.activeForeground": acc,
        "widget.border": border, "selection.background": acc + "66",
        "editor.background": vbg, "editor.foreground": fg, "editorCursor.foreground": acc,
        "editor.selectionBackground": acc + "55", "editor.inactiveSelectionBackground": acc + "2a",
        "editor.lineHighlightBackground": line, "editor.findMatchBackground": _h(p.neutral, 0.4),
        "editor.findMatchHighlightBackground": _h(p.neutral, 0.2),
        "editorLineNumber.foreground": dim, "editorLineNumber.activeForeground": fg,
        "editorIndentGuide.background1": border, "editorWhitespace.foreground": border,
        "editorError.foreground": _h(p.negative), "editorWarning.foreground": _h(p.neutral),
        "editorInfo.foreground": acc,
        "editorWidget.background": wbg, "editorWidget.border": border, "editorHoverWidget.background": wbg,
        "editorSuggestWidget.background": wbg, "editorSuggestWidget.selectedBackground": acc,
        "editorSuggestWidget.selectedForeground": on,
        "editorGroupHeader.tabsBackground": wbg, "editorGroup.border": border,
        "tab.activeBackground": vbg, "tab.activeForeground": fg, "tab.inactiveBackground": wbg,
        "tab.inactiveForeground": dim, "tab.border": border, "tab.activeBorderTop": acc,
        "sideBar.background": wbg, "sideBar.foreground": _h(win["ForegroundNormal"]), "sideBar.border": border,
        "sideBarSectionHeader.background": wbg, "sideBarTitle.foreground": _h(win["ForegroundNormal"]),
        "activityBar.background": wbg, "activityBar.foreground": _h(win["ForegroundNormal"]),
        "activityBar.inactiveForeground": dim, "activityBar.activeBorder": acc,
        "activityBarBadge.background": acc, "activityBarBadge.foreground": on,
        "titleBar.activeBackground": _h(wm["activeBackground"]), "titleBar.activeForeground": _h(wm["activeForeground"]),
        "titleBar.inactiveBackground": _h(wm["inactiveBackground"]),
        "titleBar.inactiveForeground": _h(wm["inactiveForeground"]),
        "statusBar.background": _h(head["BackgroundNormal"]), "statusBar.foreground": _h(head["ForegroundNormal"]),
        "statusBar.border": border, "statusBar.debuggingBackground": _h(p.neutral),
        "statusBarItem.remoteBackground": acc, "statusBarItem.remoteForeground": on,
        "panel.background": wbg, "panel.border": border, "panelTitle.activeBorder": acc,
        "list.activeSelectionBackground": acc, "list.activeSelectionForeground": on,
        "list.inactiveSelectionBackground": acc + "40", "list.hoverBackground": line,
        "list.highlightForeground": acc, "list.focusOutline": acc,
        "input.background": vbg, "input.foreground": fg, "input.border": border,
        "inputOption.activeBorder": acc, "dropdown.background": _h(btn["BackgroundNormal"]),
        "dropdown.foreground": _h(btn["ForegroundNormal"]), "dropdown.border": border,
        "button.background": acc, "button.foreground": on, "button.hoverBackground": _h(sel["BackgroundAlternate"]),
        "button.secondaryBackground": _h(btn["BackgroundNormal"]),
        "button.secondaryForeground": _h(btn["ForegroundNormal"]),
        "badge.background": acc, "badge.foreground": on, "progressBar.background": acc,
        "scrollbarSlider.background": _h(win["ForegroundNormal"], 0.15),
        "scrollbarSlider.hoverBackground": _h(win["ForegroundNormal"], 0.25),
        "scrollbarSlider.activeBackground": acc + "99",
        "menu.background": wbg, "menu.foreground": _h(win["ForegroundNormal"]),
        "menu.selectionBackground": acc, "menu.selectionForeground": on,
        "notifications.background": wbg, "quickInput.background": wbg,
        "gitDecoration.modifiedResourceForeground": _h(p.neutral),
        "gitDecoration.untrackedResourceForeground": _h(p.positive),
        "gitDecoration.deletedResourceForeground": _h(p.negative),
        "terminal.background": a["background"], "terminal.foreground": a["foreground"],
        "terminalCursor.foreground": acc,
    }
    for i, n in enumerate(ANSI_NAMES):
        colors[f"terminal.ansi{n.title()}"] = a[f"color{i}"]
        colors[f"terminal.ansiBright{n.title()}"] = a[f"color{i + 8}"]

    def tok(scope, color, style=""):
        return {"scope": scope, "settings": {"foreground": color, **({"fontStyle": style} if style else {})}}
    tokens = [
        tok(["comment", "punctuation.definition.comment"], dim, "italic"),
        tok(["string", "string.quoted", "punctuation.definition.string"], a["color2"]),
        tok(["constant.numeric", "constant.language", "constant.character", "support.constant"], a["color3"]),
        tok(["keyword", "storage", "storage.type", "keyword.control"], a["color5"]),
        tok(["entity.name.function", "support.function", "meta.function-call"], a["color4"]),
        tok(["entity.name.type", "entity.name.class", "support.type", "support.class"], a["color6"]),
        tok(["variable.parameter", "variable.language"], a["color11"], "italic"),
        tok(["entity.name.tag", "markup.heading"], acc),
        tok(["entity.other.attribute-name"], a["color3"]),
        tok(["invalid"], _h(p.negative)),
        tok(["markup.inserted"], _h(p.positive)), tok(["markup.deleted"], _h(p.negative)),
    ]
    return {"name": theme.name, "type": "dark" if theme.dark else "light", "semanticHighlighting": True,
            "colors": colors, "tokenColors": tokens}


def _semver(v: str) -> str:
    nums = [int(x) for x in re.findall(r"\d+", v)][:3]
    return ".".join(map(str, nums + [0] * (3 - len(nums)))) if nums else "1.0.0"


def vscode_id(theme: Theme) -> str:
    return f"kdec-{theme.slug.lower()}"


def vsix(theme: Theme) -> bytes:
    """A VS Code extension package with the color theme (`code --install-extension file.vsix`)."""
    ext, ver = vscode_id(theme), _semver(theme.version)
    pkg = {
        "name": ext, "displayName": f"{theme.name} (kde-customizer)", "publisher": "kdecustomizer",
        "description": f"{theme.name} colors, generated by kde-customizer", "version": ver,
        "engines": {"vscode": "^1.60.0"}, "categories": ["Themes"],
        "contributes": {"themes": [{"label": theme.name, "uiTheme": "vs-dark" if theme.dark else "vs",
                                    "path": f"./themes/{ext}-color-theme.json"}]},
    }
    manifest = f"""<?xml version="1.0" encoding="utf-8"?>
<PackageManifest Version="2.0.0" xmlns="http://schemas.microsoft.com/developer/vsx-schema/2011">
  <Metadata>
    <Identity Language="en-US" Id="{ext}" Version="{ver}" Publisher="kdecustomizer"/>
    <DisplayName>{theme.name} (kde-customizer)</DisplayName>
    <Description xml:space="preserve">{theme.name} colors, generated by kde-customizer</Description>
    <Categories>Themes</Categories>
    <Properties><Property Id="Microsoft.VisualStudio.Code.Engine" Value="^1.60.0"/></Properties>
  </Metadata>
  <Installation><InstallationTarget Id="Microsoft.VisualStudio.Code"/></Installation>
  <Dependencies/>
  <Assets><Asset Type="Microsoft.VisualStudio.Code.Manifest" Path="extension/package.json" Addressable="true"/></Assets>
</PackageManifest>
"""
    types = """<?xml version="1.0" encoding="utf-8"?>
<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types">
  <Default Extension=".json" ContentType="application/json"/>
  <Default Extension=".vsixmanifest" ContentType="text/xml"/>
</Types>
"""
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
        for name, text in [("[Content_Types].xml", types), ("extension.vsixmanifest", manifest),
                           ("extension/package.json", json.dumps(pkg, indent=2)),
                           (f"extension/themes/{ext}-color-theme.json", json.dumps(vscode_theme(theme), indent=2))]:
            info = zipfile.ZipInfo(name, date_time=(2020, 1, 1, 0, 0, 0))     # reproducible
            info.compress_type = zipfile.ZIP_DEFLATED
            z.writestr(info, text)
    return buf.getvalue()


def files(theme: Theme) -> dict[str, str | bytes]:
    """apps/<path> -> contents, for the apps enabled in [apps]."""
    a, out = theme.apps, {}
    if a.kitty:
        out[f"kitty/{theme.slug}.conf"] = kitty(theme)
    if a.alacritty:
        out["alacritty/kde-customizer.toml"] = alacritty(theme)
    if a.wezterm:
        out[f"wezterm/{theme.slug}.toml"] = wezterm(theme)
    if a.ghostty:
        out[f"ghostty/{theme.slug}"] = ghostty(theme)
    if a.vscode:
        out[f"vscode/{vscode_id(theme)}.vsix"] = vsix(theme)
    return out

