"""Boot splash — a Plymouth "script" theme in the palette (shown while booting and at disk-unlock prompts).

The theme lives in /usr/share/plymouth/themes/<name>/ and is copied into the initramfs, so applying it needs
root and an initramfs rebuild (`plymouth-set-default-theme -R`, which calls mkinitcpio/dracut). install.sh does
that through `boot/apply.sh` in its single pkexec step, and only when the theme changed.

The script shows the theme name and an accent progress bar over a palette gradient, and — the part that must
never break — the password prompt for encrypted disks (SetDisplayPasswordFunction), questions and messages.
Images are tiny PNGs written here with zlib (Plymouth's script plugin only loads PNG); no Pillow needed.
"""
from __future__ import annotations

import shlex
import struct
import zlib

from ..color import RGB, mix, parse
from ..spec import Theme


def name(theme: Theme) -> str:
    return f"kdec-{theme.slug.lower()}"


def png(w: int, h: int, pixel) -> bytes:
    """RGBA PNG; `pixel(x, y)` -> (r, g, b, a)."""
    raw = bytearray()
    for y in range(h):
        raw.append(0)
        for x in range(w):
            raw += bytes(pixel(x, y))

    def chunk(kind: bytes, data: bytes) -> bytes:
        return struct.pack(">I", len(data)) + kind + data + struct.pack(">I", zlib.crc32(kind + data) & 0xFFFFFFFF)

    return (b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", w, h, 8, 6, 0, 0, 0))
            + chunk(b"IDAT", zlib.compress(bytes(raw), 9)) + chunk(b"IEND", b""))


def _solid(c: RGB, a: int = 255) -> bytes:
    return png(4, 4, lambda x, y: (*c, a))


def _disc(c: RGB, size: int = 32) -> bytes:
    """Antialiased circle (password bullets)."""
    r = size / 2

    def px(x, y):
        d = ((x + 0.5 - r) ** 2 + (y + 0.5 - r) ** 2) ** 0.5
        return (*c, max(0, min(255, round((r - d) * 255))))
    return png(size, size, px)


def _rounded(fill: RGB, edge: RGB, w: int = 480, h: int = 64, radius: int = 12) -> bytes:
    """Rounded field with a 2px edge (password entry); scaled by the script, so keep it roughly to aspect."""
    def inside(x, y, inset):
        cx = min(max(x + 0.5, radius), w - radius)
        cy = min(max(y + 0.5, radius), h - radius)
        return ((x + 0.5 - cx) ** 2 + (y + 0.5 - cy) ** 2) ** 0.5 <= radius - inset

    def px(x, y):
        if not inside(x, y, 0):
            return (0, 0, 0, 0)
        return (*fill, 255) if inside(x, y, 2) else (*edge, 255)
    return png(w, h, px)


def _f(c: RGB) -> str:
    """Plymouth colors are 0..1 floats."""
    return ", ".join(f"{v / 255:.3f}" for v in c)


def script(theme: Theme) -> str:
    """The Plymouth .script: background, logo text, progress bar, and the password / question / message callbacks (disk
    unlock must keep working)."""
    p = theme.palette.resolved()
    bg, fg, acc = parse(p.background), parse(p.foreground), parse(p.accent)
    top, bottom = (bg, mix(bg, acc, 0.22)) if theme.boot_splash.background == "gradient" else (bg, bg)
    dim = mix(fg, bg, 0.4)
    family = (theme.fonts.general.split(",")[0].strip() if theme.fonts.general else "") or "Sans"
    text = (theme.boot_splash.text or theme.name).replace("\\", "\\\\").replace('"', '\\"')
    return f"""# Boot splash for {theme.name}, generated by kde-customizer. Plymouth script plugin.

Window.SetBackgroundTopColor({_f(top)});
Window.SetBackgroundBottomColor({_f(bottom)});

sw = Window.GetWidth();
sh = Window.GetHeight();
unit = Math.Int(sh / 48);
if (unit < 12) unit = 12;
cx = Window.GetX() + sw / 2;
cy = Window.GetY() + sh / 2;

# --- title ------------------------------------------------------------------------------------
title_image = Image.Text("{text}", {_f(fg)}, 1, "{family} Light " + Math.Int(unit * 2));
title = Sprite(title_image);
title.SetPosition(cx - title_image.GetWidth() / 2, cy - unit * 2 - title_image.GetHeight(), 10);

# --- progress bar -------------------------------------------------------------------------------
bar_w = unit * 14;
bar_h = Math.Int(unit / 4);
if (bar_h < 3) bar_h = 3;
bar_x = cx - bar_w / 2;
bar_y = cy;
track = Sprite(Image("track.png").Scale(bar_w, bar_h));
track.SetPosition(bar_x, bar_y, 10);
fill_image = Image("fill.png");
fill = Sprite();
fill.SetPosition(bar_x, bar_y, 11);

fun progress_callback(duration, progress) {{
    w = Math.Int(bar_w * progress);
    if (w < 1) w = 1;
    fill.SetImage(fill_image.Scale(w, bar_h));
}}
Plymouth.SetBootProgressFunction(progress_callback);

# --- password / question / message ---------------------------------------------------------------
entry_w = unit * 18;
entry_h = Math.Int(unit * 2.4);
entry_image = Image("entry.png").Scale(entry_w, entry_h);
bullet_size = Math.Int(unit * 0.7);
bullet_image = Image("bullet.png").Scale(bullet_size, bullet_size);
prompt = Sprite();
entry = Sprite(entry_image);
entry.SetOpacity(0);
answer = Sprite();
message = Sprite();
bullets[0] = Sprite();
bullet_count = 0;

fun show_prompt(text) {{
    img = Image.Text(text, {_f(dim)}, 1, "{family} " + Math.Int(unit * 0.9));
    prompt.SetImage(img);
    prompt.SetPosition(cx - img.GetWidth() / 2, cy + unit * 2, 20);
    prompt.SetOpacity(1);
    entry.SetPosition(cx - entry_w / 2, cy + unit * 3.5, 20);
    entry.SetOpacity(1);
}}

fun hide_bullets() {{
    for (i = 0; i < bullet_count; i++) bullets[i].SetOpacity(0);
}}

fun display_password(text, count) {{
    show_prompt(text);
    answer.SetOpacity(0);
    hide_bullets();
    max = Math.Int((entry_w - unit) / (bullet_size * 1.5));
    if (count > max) count = max;
    for (i = 0; i < count; i++) {{
        if (!bullets[i]) bullets[i] = Sprite(bullet_image);
        bullets[i].SetImage(bullet_image);
        bullets[i].SetPosition(cx - entry_w / 2 + unit / 2 + i * bullet_size * 1.5,
                               cy + unit * 3.5 + (entry_h - bullet_size) / 2, 21);
        bullets[i].SetOpacity(1);
    }}
    if (count > bullet_count) global.bullet_count = count;
}}

fun display_question(text, typed) {{
    show_prompt(text);
    hide_bullets();
    img = Image.Text(typed, {_f(fg)}, 1, "{family} " + Math.Int(unit));
    answer.SetImage(img);
    answer.SetPosition(cx - entry_w / 2 + unit / 2, cy + unit * 3.5 + (entry_h - img.GetHeight()) / 2, 21);
    answer.SetOpacity(1);
}}

fun display_normal() {{
    prompt.SetOpacity(0);
    entry.SetOpacity(0);
    answer.SetOpacity(0);
    hide_bullets();
}}

fun display_message(text) {{
    img = Image.Text(text, {_f(dim)}, 1, "{family} " + Math.Int(unit * 0.8));
    message.SetImage(img);
    message.SetPosition(cx - img.GetWidth() / 2, Window.GetY() + sh - unit * 3, 20);
}}

fun hide_message(text) {{
    message.SetOpacity(0);
}}

Plymouth.SetDisplayPasswordFunction(display_password);
Plymouth.SetDisplayQuestionFunction(display_question);
Plymouth.SetDisplayNormalFunction(display_normal);
Plymouth.SetMessageFunction(display_message);
Plymouth.SetHideMessageFunction(hide_message);
"""


def files(theme: Theme) -> dict[str, str | bytes]:
    """Theme folder contents (written to boot/<name>/)."""
    p = theme.palette.resolved()
    bg, fg, acc, surf = parse(p.background), parse(p.foreground), parse(p.accent), parse(p.surface)
    n = name(theme)
    return {
        f"{n}.plymouth": "\n".join([
            "[Plymouth Theme]",
            f"Name={theme.name}",
            f"Description=Boot splash for {theme.name}, generated by kde-customizer",
            "ModuleName=script",
            "",
            "[script]",
            f"ImageDir=/usr/share/plymouth/themes/{n}",
            f"ScriptFile=/usr/share/plymouth/themes/{n}/{n}.script",
            "",
        ]),
        f"{n}.script": script(theme),
        "track.png": _solid(mix(bg, fg, 0.16)),
        "fill.png": _solid(acc),
        "entry.png": _rounded(surf, mix(surf, acc, 0.6)),
        "bullet.png": _disc(fg),
    }


def apply_script(theme: Theme) -> str:
    """boot/apply.sh <build dir>: run as root. KDEC_BOOT_ROOT=<dir> (tests) only installs the files under it."""
    n = name(theme)
    q = shlex.quote
    return "\n".join([
        "#!/usr/bin/env bash",
        f"# Installs and selects the '{theme.name}' boot splash (Plymouth). Run as root: apply.sh <build dir>.",
        "# Generated by kde-customizer.",
        "set -euo pipefail",
        'DIR="$(cd "$1" && pwd)"',
        'ROOT="${KDEC_BOOT_ROOT:-}"',
        f"NAME={q(n)}",
        'if [[ -z "$ROOT" ]] && ! command -v plymouth-set-default-theme >/dev/null 2>&1; then',
        '  echo "Plymouth is not installed: boot splash left as is."; exit 0',
        "fi",
        'THEMES="$ROOT/usr/share/plymouth/themes"',
        'mkdir -p "$THEMES"',
        'rm -rf "$THEMES/$NAME"',
        'cp -r "$DIR/boot/$NAME" "$THEMES/"',
        'chmod -R a+rX,go-w "$THEMES/$NAME"',
        '[[ -n "$ROOT" ]] && exit 0',
        'PREV="$(plymouth-set-default-theme 2>/dev/null || true)"',
        'echo "Rebuilding the initramfs with the new boot splash (this can take a minute)…"',
        'plymouth-set-default-theme -R "$NAME"',
        'if [[ -n "$PREV" && "$PREV" != "$NAME" ]]; then',
        '  echo "Boot splash was \'$PREV\'. To go back: sudo plymouth-set-default-theme -R $PREV"',
        "fi",
        "",
    ])
