"""restore-point.sh: run by install.sh before it changes anything. It records how the desktop is set up now
and writes `restore.sh` next to that record; running it (`kdec revert`, or by hand) puts the desktop back.

Restore points live in `$XDG_STATE_HOME/kde-customizer/restore/<time>-<Slug>/` (the newest 10 are kept):
- the previous value of every config key the install writes (or `--delete` when it wasn't set);
- `~/.config/kdedefaults/` (plasma-apply-lookandfeel rewrites it: unset keys fall back to it);
- color scheme, cursors, Plasma style, icons and wallpaper, put back with the same plasma-apply-* tools;
- copies of the text configs install.sh edits (GTK, kitty, Ghostty, Alacritty), and the panel layout with --layout.
The login screen and boot splash (system files, admin password) and the VS Code extension are not reverted.
"""
from __future__ import annotations

import shlex

from ..spec import Theme

# (file, groups, key) that Look-and-Feel or install.sh write and that a plain value restores. Color scheme,
# icons, cursors and Plasma style are excluded: their plasma-apply-* tool writes the key and reloads the desktop.
BASE_KEYS: list[tuple[str, tuple[str, ...], str]] = [
    ("kdeglobals", ("KDE",), "LookAndFeelPackage"),
    ("kdeglobals", ("KDE",), "widgetStyle"),
    ("kwinrc", ("org.kde.kdecoration2",), "library"),
    ("kwinrc", ("org.kde.kdecoration2",), "theme"),
    ("kwinrc", ("org.kde.kdecoration2",), "ButtonsOnLeft"),
    ("kwinrc", ("org.kde.kdecoration2",), "ButtonsOnRight"),
    ("ksplashrc", ("KSplash",), "Engine"),
    ("ksplashrc", ("KSplash",), "Theme"),
    ("konsolerc", ("Desktop Entry",), "DefaultProfile"),
    ("$CONF/Kvantum/kvantum.kvconfig", ("General",), "theme"),
]
APPLIED_BY_TOOLS = {("kdeglobals", ("General",), "ColorScheme"), ("kdeglobals", ("Icons",), "Theme"),
                    ("kcminputrc", ("Mouse",), "cursorTheme"), ("plasmarc", ("Theme",), "name")}

# Text configs install.sh edits (kept as they were, or removed when they didn't exist).
FILES = [
    "$CONF/gtk-4.0/gtk.css", "$CONF/gtk-4.0/kde-customizer.css",
    "$CONF/kitty/kitty.conf", "$CONF/kitty/kde-customizer-theme.conf",
    "$CONF/ghostty/config", "$CONF/ghostty/config.ghostty",
    "$CONF/alacritty/alacritty.toml", "$CONF/alacritty/kde-customizer.toml",
]
LAYOUT_FILES = ["$CONF/plasma-org.kde.plasma.desktop-appletsrc", "$CONF/plasmashellrc"]
KEEP = 10

_WALLPAPER_JS = ('var d = desktops()[0]; d.currentConfigGroup = ["Wallpaper", "org.kde.image", "General"]; '
                 'print(d.wallpaperPlugin == "org.kde.image" ? d.readConfig("Image") : "")')


def keys(theme: Theme) -> list[tuple[str, tuple[str, ...], str]]:
    """Every key to record: the fixed ones + fonts + tweaks (all_tweaks), without duplicates."""
    from ..build import all_tweaks
    out = list(BASE_KEYS)
    for f, groups in all_tweaks(theme).items():
        for g, kv in groups.items():
            for k in kv:
                item = (f, tuple(g.split("/")), k)
                if item not in out and item not in APPLIED_BY_TOOLS:
                    out.append(item)
    return out


def _q(s: str) -> str:
    """Quote for bash but keep a leading $CONF expandable."""
    if s.startswith("$CONF/"):
        return '"$CONF"/' + shlex.quote(s[len("$CONF/"):])
    return shlex.quote(s)


def script(theme: Theme) -> str:
    q = shlex.quote
    s = [
        "#!/usr/bin/env bash",
        f"# Records the current desktop before '{theme.name}' is installed and writes restore.sh to put it back.",
        "# Usage: restore-point.sh [--layout]   (run by install.sh; generated by kde-customizer)",
        "set -uo pipefail",
        'CONF="${XDG_CONFIG_HOME:-$HOME/.config}"',
        'ROOT="${XDG_STATE_HOME:-$HOME/.local/state}/kde-customizer/restore"',
        'LAYOUT=0; for a in "$@"; do [[ "$a" == --layout ]] && LAYOUT=1; done',
        'command -v kreadconfig6 >/dev/null 2>&1 || { echo "kreadconfig6 missing: no restore point"; exit 0; }',
        f'RP="$ROOT/$(date +%Y%m%d-%H%M%S)-{theme.slug}"',
        'B="$RP"; n=0; while [[ -e "$RP" ]]; do n=$((n + 1)); RP="$B-$n"; done',
        'mkdir -p "$RP/files"',
        'R="$RP/restore.sh"',
        "cat > \"$R\" <<'KDEC_EOF'",
        "#!/usr/bin/env bash",
        "# Puts the desktop back the way it was before a kde-customizer theme was installed.",
        "set -u",
        'RP="$(cd "$(dirname "$0")" && pwd)"',
        'CONF="${XDG_CONFIG_HOME:-$HOME/.config}"',
        "KDEC_EOF",
        f'echo "# taken before installing {theme.name}, $(date)" >> "$R"',
        "",
        "# Look-and-Feel defaults (unset keys fall back to these)",
        'if [[ -d "$CONF/kdedefaults" ]]; then',
        '  cp -a "$CONF/kdedefaults" "$RP/kdedefaults"',
        '  echo \'rm -rf "$CONF/kdedefaults"; cp -a "$RP/kdedefaults" "$CONF/kdedefaults"\' >> "$R"',
        "else",
        '  echo \'rm -rf "$CONF/kdedefaults"\' >> "$R"',
        "fi",
        "",
        "# what the plasma-apply-* tools set (they also reload the running desktop)",
        "rd() { kreadconfig6 --file \"$1\" --group \"$2\" --key \"$3\" 2>/dev/null || true; }",
        'V="$(rd kdeglobals General ColorScheme)"',
        'echo "plasma-apply-colorscheme $(printf %q "${V:-BreezeLight}") || true" >> "$R"',
        'V="$(rd kcminputrc Mouse cursorTheme)"',
        'echo "plasma-apply-cursortheme $(printf %q "${V:-breeze_cursors}") || true" >> "$R"',
        'V="$(rd plasmarc Theme name)"',
        'echo "plasma-apply-desktoptheme $(printf %q "${V:-default}") || true" >> "$R"',
        'V="$(rd kdeglobals Icons Theme)"',
        'echo "CHANGEICONS=\\"\\$(ls /usr/lib/plasma-changeicons /usr/lib/*/plasma-changeicons '
        '/usr/libexec/plasma-changeicons 2>/dev/null | head -n1 || true)\\"" >> "$R"',
        'echo "[[ -n \\"\\$CHANGEICONS\\" ]] && \\"\\$CHANGEICONS\\" $(printf %q "${V:-breeze}") || true" >> "$R"',
        "",
        "# plain keys: the old value, or deleted when it wasn't set",
        "key() {  # key FILE KEY GROUP...",
        '  local f="$1" k="$2" a=() g v; shift 2',
        '  for g in "$@"; do a+=(--group "$g"); done',
        "  # the user's own file only (no XDG_CONFIG_DIRS cascade): a key set nowhere but kdedefaults stays unset",
        '  v="$(XDG_CONFIG_DIRS=/nonexistent kreadconfig6 --file "$f" "${a[@]}" --key "$k" --default __KDEC_UNSET__ '
        '2>/dev/null)" || v=__KDEC_UNSET__',
        '  local line="kwriteconfig6 --notify --file $(printf %q "$f") $(printf -- \'--group %q \' "$@")--key $(printf %q "$k")"',
        '  if [[ "$v" == __KDEC_UNSET__ ]]; then echo "$line --delete" >> "$R"; else echo "$line $(printf %q "$v")" >> "$R"; fi',
        "}",
    ]
    for f, groups, k in keys(theme):
        s.append(f"key {_q(f)} {q(k)} {' '.join(q(g) for g in groups)}")
    s += [
        "",
        "# text configs install.sh edits",
        "keepfile() {",
        '  n=$((n + 1))',
        '  if [[ -e "$1" ]]; then',
        '    cp -L "$1" "$RP/files/$n"',
        '    echo "mkdir -p $(printf %q "$(dirname "$1")"); cat \\"\\$RP/files/$n\\" > $(printf %q "$1")" >> "$R"',
        "  else",
        '    echo "rm -f $(printf %q "$1")" >> "$R"',
        "  fi",
        "}",
        "n=0",
    ]
    s += [f"keepfile {_q(f)}" for f in FILES]
    from . import mozilla
    roots = " ".join(f'"{r}"' for app in ("firefox", "thunderbird") for r in mozilla.ROOTS[app])
    s += [mozilla.PROFILES_FN,
          "while IFS= read -r P; do",
          f'  keepfile "$P/chrome/userChrome.css"; keepfile "$P/chrome/{mozilla.FILE}"; keepfile "$P/user.js"',
          f"done < <(moz_profiles {roots})"]
    s += [
        "",
        "if (( LAYOUT )); then",
        "  # --layout replaces the panels: keep the old layout (it holds the wallpaper too)",
        "  echo 'kquitapp6 plasmashell >/dev/null 2>&1 || true' >> \"$R\"",
    ]
    s += [f"  keepfile {_q(f)}" for f in LAYOUT_FILES]
    s += [
        "  echo '(setsid plasmashell >/dev/null 2>&1 &)' >> \"$R\"",
        "else",
        "  WP=\"$(qdbus6 org.kde.plasmashell /PlasmaShell org.kde.PlasmaShell.evaluateScript "
        + q(_WALLPAPER_JS) + ' 2>/dev/null || true)"',
        '  WP="${WP#file://}"',
        '  [[ -n "$WP" && -e "$WP" ]] && echo "plasma-apply-wallpaperimage $(printf %q "$WP") >/dev/null || true" >> "$R"',
        "fi",
        "",
        "cat >> \"$R\" <<'KDEC_EOF'",
        "# tell running apps the widget style changed, reload KWin",
        "dbus-send --session --type=signal /KGlobalSettings org.kde.KGlobalSettings.notifyChange int32:2 int32:0 "
        "2>/dev/null || true",
        "qdbus6 org.kde.KWin /KWin reconfigure >/dev/null 2>&1 || true",
        'echo "Desktop restored. (Login screen, boot splash and VS Code extensions are not changed by this.)"',
        "KDEC_EOF",
        'chmod +x "$R"',
        f'ls -1d "$ROOT"/*/ 2>/dev/null | sort | head -n -{KEEP} | xargs -r -d "\\n" rm -rf',
        'echo "restore point: $RP  (undo with: kdec revert, or bash \\"$R\\")"',
        "",
    ]
    return "\n".join(s)
