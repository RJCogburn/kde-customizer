"""Snapshot: read the running desktop's configuration back into a Theme spec.

Reads the same files Plasma does, merged the way KConfig cascades them: `$XDG_CONFIG_DIRS` (lowest priority
last listed, e.g. /etc/xdg, then ~/.config/kdedefaults written by Look-and-Feel) under `$XDG_CONFIG_HOME`.

- palette: kdeglobals [Colors:*] (+ [General] AccentColor when set)
- installed names: icons, cursors, widget style, Plasma style, splash, window decoration, fonts
- wallpaper: the image of screen 0's desktop containment
- panels: screen 0's panels from plasma-org.kde.plasma.desktop-appletsrc + plasmashellrc [PlasmaViews]

Parts built by kde-customizer (they carry a "generated by kde-customizer" marker) come back as
`generate = true`, with the icon/cursor base they were made from; their shape options come back as defaults.
"""
from __future__ import annotations

import os
import re
from pathlib import Path

from . import color, spec
from .spec import Panel, Theme

_MARK = "generated by kde-customizer"
_FROM = re.compile(r"Generated by kde-customizer from (.+)", re.I)
_LOCATIONS = {3: "top", 4: "bottom", 5: "left", 6: "right"}
_LENGTH = {0: "fill", 1: "fit"}
_IMAGE_EXT = (".png", ".jpg", ".jpeg", ".webp", ".avif", ".jxl", ".svg")

Config = dict[tuple[str, ...], dict[str, str]]


def _config_dirs() -> list[Path]:
    """Highest priority first."""
    home = Path(os.environ.get("XDG_CONFIG_HOME") or Path.home() / ".config")
    dirs = [d for d in os.environ.get("XDG_CONFIG_DIRS", "/etc/xdg").split(":") if d]
    return [home, *map(Path, dirs)]


def _data_dirs() -> list[Path]:
    home = Path(os.environ.get("XDG_DATA_HOME") or Path.home() / ".local/share")
    dirs = [d for d in os.environ.get("XDG_DATA_DIRS", "/usr/local/share:/usr/share").split(":") if d]
    return [home, *map(Path, dirs)]


def parse_kconfig(text: str) -> Config:
    out: Config = {}
    groups: tuple[str, ...] = ()
    for line in text.splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        if line.startswith("["):
            groups = tuple(re.findall(r"\[([^\]]*)\]", line))
            out.setdefault(groups, {})
        elif "=" in line:
            k, v = line.split("=", 1)
            k = re.sub(r"\[\$[a-z]+\]$", "", k.strip())       # key[$e] / key[$i] flags
            out.setdefault(groups, {})[k] = v.strip()
    return out


def read_config(name: str, dirs: list[Path] | None = None) -> Config:
    """A config file merged across the cascade (later = higher priority wins)."""
    merged: Config = {}
    for d in reversed(dirs or _config_dirs()):
        f = d / name
        if f.is_file():
            try:
                for g, kv in parse_kconfig(f.read_text(errors="replace")).items():
                    merged.setdefault(g, {}).update(kv)
            except OSError:
                pass
    return merged


def _get(cfg: Config, groups: tuple[str, ...], key: str, default: str = "") -> str:
    return cfg.get(groups, {}).get(key, default)


def _hex(value: str) -> str | None:
    try:
        parts = [int(x) for x in value.split(",")[:3]]
    except ValueError:
        return value if re.fullmatch(r"#[0-9a-fA-F]{6}", value) else None
    if len(parts) != 3:
        return None
    return color.to_hex(tuple(max(0, min(255, p)) for p in parts))


def _font(qfont: str) -> str:
    """'Inter,10,-1,5,400,...' -> 'Inter,10'."""
    if not qfont:
        return ""
    parts = qfont.split(",")
    if len(parts) < 2:
        return parts[0]
    size = parts[1]
    try:
        size = f"{float(size):g}"
    except ValueError:
        size = "10"
    return f"{parts[0]},{size}"


def _find(sub: str, name: str) -> Path | None:
    extra = [Path.home() / ".icons"] if sub == "icons" else []
    for d in [*extra, *(b / sub for b in _data_dirs())]:
        if (d / name).exists():
            return d / name
    return None


def _generated_from(theme_dir: Path | None) -> str | None:
    """Base name of an icon/cursor theme kde-customizer generated, else None."""
    if not theme_dir or not (theme_dir / "index.theme").is_file():
        return None
    m = _FROM.search((theme_dir / "index.theme").read_text(errors="replace"))
    return m.group(1).strip() if m else None


def _marked(meta: Path) -> bool:
    try:
        return _MARK in meta.read_text(errors="replace").lower()
    except OSError:
        return False


def _palette(globals_: Config) -> spec.Palette:
    p = spec.Palette()
    # field -> where to read it, first present wins (surface = what colors.scheme() writes as Window's alternate)
    pick = {
        "background": [("Colors:Window", "BackgroundNormal")],
        "surface": [("Colors:Window", "BackgroundAlternate"), ("Colors:Button", "BackgroundNormal")],
        "foreground": [("Colors:Window", "ForegroundNormal")],
        "accent": [("General", "AccentColor"), ("Colors:Selection", "BackgroundNormal")],
        "positive": [("Colors:View", "ForegroundPositive")],
        "neutral": [("Colors:View", "ForegroundNeutral")],
        "negative": [("Colors:View", "ForegroundNegative")],
        "link": [("Colors:View", "ForegroundLink")],
        "visited": [("Colors:View", "ForegroundVisited")],
    }
    for field, places in pick.items():
        for g, k in places:
            if (c := _hex(_get(globals_, (g,), k))):
                setattr(p, field, c)
                break
    if p.link == p.accent:
        p.link = ""                     # default: follows the accent
    return p


def _wallpaper(applets: Config) -> str:
    """Screen 0's desktop image (a file, or the best image inside a wallpaper package)."""
    best = None
    for g, kv in applets.items():
        if len(g) == 2 and g[0] == "Containments" and kv.get("plugin", "") != "org.kde.panel" \
                and kv.get("activityId") and kv.get("wallpaperplugin") == "org.kde.image":
            screen = int(kv.get("lastScreen", "0") or 0)
            if best is None or screen < best[0]:
                best = (screen, g[1])
    if not best:
        return ""
    img = _get(applets, ("Containments", best[1], "Wallpaper", "org.kde.image", "General"), "Image")
    path = Path(re.sub(r"^file://", "", img)) if img else None
    if not path or not path.exists():
        return ""
    if path.is_dir():                   # wallpaper package: largest image in contents/images
        imgs = [f for f in (path / "contents/images").glob("*") if f.suffix.lower() in _IMAGE_EXT]
        if not imgs:
            return ""
        path = max(imgs, key=lambda f: f.stat().st_size)
    return str(path)


def _panels(applets: Config, shell: Config) -> list[Panel]:
    """Panels on the lowest-numbered screen that has any (layout.js creates them on one screen)."""
    found = []
    for g, kv in applets.items():
        if len(g) == 2 and g[0] == "Containments" and kv.get("plugin") == "org.kde.panel":
            found.append((int(kv.get("lastScreen", "0") or 0), g[1], kv))
    if not found:
        return []
    screen = min(s for s, _, _ in found)
    out = []
    for _, cid, kv in sorted((f for f in found if f[0] == screen), key=lambda f: int(f[1])):
        order = _get(applets, ("Containments", cid, "General"), "AppletOrder")
        ids = [x for x in order.split(";") if x] if order else sorted(
            (g[3] for g in applets if len(g) == 4 and g[:3] == ("Containments", cid, "Applets")), key=int)
        widgets = [p for a in ids if (p := _get(applets, ("Containments", cid, "Applets", a), "plugin"))]
        view = shell.get(("PlasmaViews", f"Panel {cid}"), {})
        thickness = _get(shell, ("PlasmaViews", f"Panel {cid}", "Defaults"), "thickness")
        align = int(view.get("alignment", "4") or 4)
        out.append(Panel(
            location=_LOCATIONS.get(int(kv.get("location", "4") or 4), "bottom"),
            height=int(thickness) if thickness.isdigit() else 44,
            floating=view.get("floating", "1") != "0",
            alignment="left" if align == 1 else "right" if align == 2 else "center",
            length_mode=_LENGTH.get(int(view.get("panelLengthMode", "0") or 0), "fill"),
            widgets=widgets or Panel().widgets,
        ))
    return out


def take(name: str = "My Desktop") -> Theme:
    """The current desktop as a Theme spec named `name`."""
    g = read_config("kdeglobals")
    t = Theme(name=name)
    t.id = "org.kdecustomizer." + (re.sub(r"[^a-z0-9]+", "", name.lower()) or "snapshot")
    t.description = "Snapshot of a Plasma desktop"
    t.palette = _palette(g)

    icons = _get(g, ("Icons",), "Theme", "breeze")
    if (base := _generated_from(_find("icons", icons))):
        t.iconset.generate, t.iconset.base, t.icons = True, base, base
    else:
        t.icons = icons

    cursors = _get(read_config("kcminputrc"), ("Mouse",), "cursorTheme", "breeze_cursors")
    if (base := _generated_from(_find("icons", cursors))):
        t.cursorset.generate, t.cursorset.base, t.cursors = True, base, base
    else:
        t.cursors = cursors

    style = _get(g, ("KDE",), "widgetStyle", "Breeze")
    if style.lower() == "kvantum":
        kv_theme = _get(read_config("Kvantum/kvantum.kvconfig"), ("General",), "theme")
        kv_dir = (Path(os.environ.get("XDG_CONFIG_HOME") or Path.home() / ".config") / "Kvantum" / kv_theme)
        t.widgets.generate = bool(kv_theme) and _marked(kv_dir / f"{kv_theme}.kvconfig")
        t.widget_style = "Breeze"
    else:
        t.widget_style = style

    plasma = _get(read_config("plasmarc"), ("Theme",), "name", "default")
    pdir = _find("plasma/desktoptheme", plasma)
    if pdir and _marked(pdir / "metadata.json"):
        t.plasma.generate = True
    else:
        t.plasma_style = plasma

    splash = read_config("ksplashrc")
    sp = _get(splash, ("KSplash",), "Theme", "org.kde.Breeze")
    if _get(splash, ("KSplash",), "Engine", "KSplashQML") == "none":
        sp = "None"
    lnf = _get(g, ("KDE",), "LookAndFeelPackage")
    if sp == lnf and lnf.startswith("org.kdecustomizer.") and (ld := _find("plasma/look-and-feel", lnf)) \
            and (ld / "contents/splash/Splash.qml").is_file():
        t.splash_screen.generate = True
    else:
        t.splash = sp

    kwin = read_config("kwinrc")
    d = ("org.kde.kdecoration2",)
    t.decoration.library = _get(kwin, d, "library", "org.kde.breeze")
    t.decoration.theme = _get(kwin, d, "theme", "Breeze")
    t.decoration.buttons_left = _get(kwin, d, "ButtonsOnLeft", "M")
    t.decoration.buttons_right = _get(kwin, d, "ButtonsOnRight", "IAX")
    m = re.fullmatch(r"__aurorae__svg__(.+)", t.decoration.theme)
    if m and (ad := _find("aurorae/themes", m.group(1))) and _marked(ad / "metadata.json"):
        t.decoration.generate = True
        t.decoration.library, t.decoration.theme = spec.Decoration.library, spec.Decoration.theme

    f = t.fonts
    f.general = _font(_get(g, ("General",), "font"))
    f.fixed = _font(_get(g, ("General",), "fixed"))
    f.small = _font(_get(g, ("General",), "smallestReadableFont"))
    f.toolbar = _font(_get(g, ("General",), "toolBarFont"))
    f.menu = _font(_get(g, ("General",), "menuFont"))
    f.window_title = _font(_get(g, ("WM",), "activeFont"))

    applets = read_config("plasma-org.kde.plasma.desktop-appletsrc")
    t.wallpaper = _wallpaper(applets)
    panels = _panels(applets, read_config("plasmashellrc"))
    if panels:
        t.panels = panels
    return t


def summary(t: Theme) -> str:
    gen = [n for n, on in [("Plasma style", t.plasma.generate), ("icons", t.iconset.generate),
                           ("cursors", t.cursorset.generate), ("app style", t.widgets.generate),
                           ("window decoration", t.decoration.generate),
                           ("splash", t.splash_screen.generate)] if on]
    lines = [f"palette: background {t.palette.background}, accent {t.palette.accent}",
             f"{len(t.panels)} panel(s), wallpaper: {t.wallpaper or 'none'}"]
    if gen:
        lines.append("made by kde-customizer (generate = true, shape options at defaults): " + ", ".join(gen))
    return "\n".join(lines)
