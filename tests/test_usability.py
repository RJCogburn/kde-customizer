@gui
def test_start_page_cards_fill_the_width_without_scrolling(qapp):
    from PySide6.QtWidgets import QScrollArea
    from kdecustomizer.gui.start import Cards, StartPage
    library.add_recent(EXAMPLE)
    page = StartPage()
    page.resize(1400, 1100)
    page.show()
    for _ in range(40):
        qapp.processEvents()
    grid = page.starters
    per_row = (grid.viewport().width() - 4) // Cards.MIN_CELL
    first_row = [i for i in range(grid.count()) if grid.visualItemRect(grid.item(i)).top() ==
                 grid.visualItemRect(grid.item(0)).top()]
    assert len(first_row) == per_row                           # as many columns as fit, no early wrap
    assert grid.gridSize().width() * per_row <= grid.viewport().width()
    last = grid.visualItemRect(grid.item(grid.count() - 1))
    assert last.bottom() <= grid.height() <= last.bottom() + 8  # no empty band under the last row
    area = page.findChild(QScrollArea)
    assert not area.verticalScrollBar().isVisible()            # everything fits: no scrollbar
    page.close()


@gui
def test_problems_strip_and_undo_redo(blank, qapp):
    blank.load(EXAMPLE)
    blank._update_problems()
    assert "contrast" not in blank.problems.text()            # (the test box has no themes installed: warnings)
    fg = blank.theme.palette.foreground
    blank.colors["foreground"].set(blank.theme.palette.background)
    blank.changed()
    blank._update_problems()
    assert blank.problems.isVisibleTo(blank) and "contrast" in blank.problems.text()
    blank.problems.linkActivated.emit("tab:1")
    assert blank.tabs.currentIndex() == 1
    blank._commit()
    blank.text["name"].setText("Renamed")
    blank._commit()
    blank.undo()
    assert blank.theme.name == "Midnight" and blank.theme.palette.foreground != fg
    blank.undo()
    assert blank.theme.palette.foreground == fg and not blank.undo_act.isEnabled()
    blank.redo()
    blank.redo()
    assert blank.theme.name == "Renamed" and not blank.redo_act.isEnabled()
    blank.text["name"].setText("Again")
    blank._commit()
    assert not blank._redo_stack                              # a new edit drops the redo steps


