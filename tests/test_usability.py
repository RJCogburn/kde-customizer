# --- palette from an image ----------------------------------------------------------------------
def _pixels(base, spot, share=0.1, n=3000):
    k = int(n * share)
    return [spot] * k + [base] * (n - k)


def test_dark_image_gives_readable_dark_palette():
    p = imagepalette.extract(_pixels((20, 30, 70), (240, 130, 30)))       # navy with orange
    assert color.is_dark(p.background)
    assert color.contrast(p.foreground, p.background) >= 7 and color.contrast(p.foreground, p.surface) >= 4.5
    assert color.contrast(p.accent, p.background) >= 3.5
    r, g, b = color.parse(p.accent)
    assert r > g > b                                                       # orange, not the navy
    _, _, bb = color.parse(p.background)
    assert bb > color.parse(p.background)[0]                               # background keeps the blue hue
    for c in (p.positive, p.neutral, p.negative):
        assert color.contrast(c, p.background) >= 3


def test_light_image_and_forced_mode():
    light = imagepalette.extract(_pixels((235, 225, 200), (40, 140, 60)))
    assert not color.is_dark(light.background) and color.contrast(light.accent, light.background) >= 3.5
    assert color.is_dark(imagepalette.extract(_pixels((235, 225, 200), (40, 140, 60)), dark=True).background)
    gray = imagepalette.extract(_pixels((120, 120, 120), (130, 130, 130)), base=spec.Palette(accent="#e0447a"))
    r, g, b = color.parse(gray.accent)
    assert r > b > g                                                       # gray image: keeps the old accent hue


@pytest.mark.skipif(not pyside6(), reason="needs PySide6 (or Pillow) to read images")
def test_cli_palette(tmp_path, qapp, capsys):
    from PySide6.QtGui import QColor, QImage
    img = QImage(64, 64, QImage.Format_RGB32)
    img.fill(QColor("#1a2a4a"))
    for x in range(10):
        for y in range(64):
            img.setPixelColor(x, y, QColor("#e85d9a"))
    img.save(str(tmp_path / "wp.png"))
    f = tmp_path / "t.toml"
    spec.save(spec.Theme(name="Pic", wallpaper=str(tmp_path / "wp.png")), f)
    assert cli.main(["palette", str(f), "--light"]) == 0
    t = spec.load(f)
    assert not t.dark and "accent" in capsys.readouterr().out
    assert cli.main(["palette", str(f), "--dry-run"]) == 0 and spec.load(f).palette == t.palette


