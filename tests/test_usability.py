# --- recent + starters --------------------------------------------------------------------------
def test_recent_list(tmp_path):
    files = []
    for i in range(14):
        f = tmp_path / f"t{i}.toml"
        f.write_text("")
        files.append(f)
        library.add_recent(f)
    assert library.recent()[0] == files[-1].resolve() and len(library.recent()) == library.MAX_RECENT
    library.add_recent(files[5])                            # reopened: moves to the top, no duplicate
    assert library.recent()[0] == files[5].resolve() and len(library.recent()) == library.MAX_RECENT
    files[5].unlink()                                       # deleted files drop out
    assert files[5].resolve() not in library.recent()
    library.remove_recent(files[-1])
    assert files[-1].resolve() not in library.recent()


def test_starters_are_readable_and_distinct():
    paths = library.starters()
    assert len(paths) >= 8
    themes = [spec.load(p) for p in paths]
    assert len({t.id for t in themes}) == len(themes) and len({t.palette.accent for t in themes}) == len(themes)
    assert any(t.dark for t in themes) and any(not t.dark for t in themes)
    for t in themes:
        assert not [p for p in ai.check(t, {}) if "contrast" in p], t.name
        assert not spec.is_placeholder_name(t.name) and t.description


# --- installed themes ---------------------------------------------------------------------------
def _install(theme: spec.Theme, marker: bool = True) -> Path:
    """What install.sh leaves in $DATA / $CONF for a theme (without running it)."""
    data, conf = Path(os.environ["XDG_DATA_HOME"]), Path(os.environ["XDG_CONFIG_HOME"])
    lnf = data / "plasma/look-and-feel" / theme.id
    (lnf / "contents").mkdir(parents=True)
    meta = json.loads(lookandfeel.metadata(theme))
    if not marker:
        del meta["X-KDE-Customizer-Slug"]
    (lnf / "metadata.json").write_text(json.dumps(meta))
    (lnf / "contents/defaults").write_text(lookandfeel.defaults(theme))
    s = theme.slug
    for f in (f"color-schemes/{s}.colors", f"konsole/{s}.profile", f"wallpapers/{s}/w.jpg",
              f"icons/{s}-Cursors/index.theme"):
        (data / f).parent.mkdir(parents=True, exist_ok=True)
        (data / f).write_text("x")
    style = data / "plasma/desktoptheme" / s
    style.mkdir(parents=True)
    (style / "metadata.json").write_text('{"KPlugin": {"Description": "generated by kde-customizer"}}')
    kv = conf / "Kvantum" / s
    kv.mkdir(parents=True)
    (kv / f"{s}.kvconfig").write_text("")
    (kv / f"{s}.svg").write_text("")
    return lnf


def test_installed_lists_groups_and_removes(midnight):
    from kdecustomizer import variant
    _install(midnight)
    _install(variant.opposite(midnight))
    other = spec.Theme(name="Someone Else", id="com.example.else")       # not ours: no marker, foreign id
    _install(other, marker=False)
    data = Path(os.environ["XDG_DATA_HOME"])
    (data / "plasma/desktoptheme/Lookalike").mkdir(parents=True)         # same-named style, not ours

    ts = installed.themes()
    assert [t.name for t in ts] == ["Midnight"]
    t = ts[0]
    assert [v.name for v in t.variants] == ["Midnight Light"]
    names = {p.name for p in t.parts()}
    assert {"org.kdecustomizer.midnight", "Midnight.colors", "Midnight.profile", "Midnight", "Midnight-Cursors",
            "org.kdecustomizer.midnightlight", "MidnightLight.colors"} <= names
    assert not t.in_use()

    conf = Path(os.environ["XDG_CONFIG_HOME"])
    (conf / "kdeglobals").write_text("[KDE]\nLookAndFeelPackage=org.kdecustomizer.midnightlight\n")
    assert t.in_use() == ["it is the current global theme"]
    with pytest.raises(RuntimeError):
        installed.remove(t)
    (conf / "kdeglobals").write_text("[General]\nColorScheme=Breeze\n")

    gone = installed.remove(t)
    assert all(not p.exists() for p in gone)
    assert installed.themes() == []
    assert (data / "plasma/look-and-feel/com.example.else").is_dir()      # the other theme is untouched
    assert (data / "color-schemes/SomeoneElse.colors").exists()


