@gui
def test_apply_dialog_keep_or_undo(tmp_path, qapp, monkeypatch):
    from kdecustomizer.gui import apply_dialog
    from kdecustomizer import restorepoints
    monkeypatch.setattr(apply_dialog, "KEEP_SECONDS", 1)
    point = restorepoints.root() / "20261126-120000-Test"
    script = tmp_path / "install.sh"
    script.write_text(f"""#!/usr/bin/env bash
mkdir -p '{point}'
printf 'touch {tmp_path}/restored\\n' > '{point}/restore.sh'
echo "==> color scheme"
echo "==> login screen"
echo "already up to date"
echo "==> applying"
echo Done.
""")
    script.chmod(0o755)

    def run(dlg, until):
        end = time.time() + 15
        while not until() and time.time() < end:
            qapp.processEvents()
            time.sleep(0.01)

    dlg = apply_dialog.ApplyDialog(None, "Test", script, [], True)
    run(dlg, lambda: dlg._phase == "keep")
    texts = [dlg.steps.item(i).text() for i in range(dlg.steps.count())]
    assert texts[0] == "Color scheme" and "already up to date" in texts[1] and texts[2] == "Applying the theme"
    assert dlg.keep.isVisibleTo(dlg) and dlg.note.isVisibleTo(dlg)
    run(dlg, lambda: dlg._phase == "done")                    # no answer: it goes back by itself
    assert (tmp_path / "restored").exists() and not point.exists()
    assert dlg.result_text == "Desktop restored."

    (tmp_path / "restored").unlink()
    dlg = apply_dialog.ApplyDialog(None, "Test", script, [], False)
    run(dlg, lambda: dlg._phase == "keep")
    dlg.keep.click()
    assert dlg.result_text == "Applied." and not (tmp_path / "restored").exists() and point.exists()

    bad = tmp_path / "bad.sh"
    bad.write_text("#!/bin/sh\necho '==> color scheme'\nexit 3\n")
    bad.chmod(0o755)
    dlg = apply_dialog.ApplyDialog(None, "Test", bad, [], False)
    run(dlg, lambda: dlg._phase == "done")
    assert "exit 3" in dlg.result_text and dlg.details.isChecked()


